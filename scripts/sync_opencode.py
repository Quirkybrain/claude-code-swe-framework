#!/usr/bin/env python3
"""Generate OpenCode V2 instructions and agents from the Claude Code sources."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
SOURCE_AGENTS = ROOT / ".claude" / "agents"
TARGET_AGENTS = ROOT / ".opencode" / "agents"
READ_ONLY = {
    "asset-analyst",
    "debug-specialist",
    "quality-reviewer",
    "system-verifier",
}
HEADER = "<!-- Generated by scripts/sync_opencode.py; edit CLAUDE.md instead. -->\n"
AGENT_HEADER = "<!-- Generated by scripts/sync_opencode.py; edit .claude/agents/<name>.md instead. -->"
BRIDGE = """# OpenCode V2 runtime bridge

This is the OpenCode entry point for the framework below. Apply the framework's
engineering rules with these runtime mappings:

- The main session is the Stage Orchestrator. In STANDARD/STRICT, use the native
  `subagent` tool with `agent: <specialist-name>` and a prompt containing the
  exact `HANDOFF: state/handoffs/<task>.json` line. Do not use generic agents
  for specialist deliverables. The project plugin checks this handoff before
  dispatch.
- The 15 specialist definitions live in `.opencode/agents/`. Their source is
  `.claude/agents/`; regenerate after changing a source agent.
- Load `.claude/skills/<name>/SKILL.md` through OpenCode's native `skill` tool
  when a procedure is needed. Read the applicable `.claude/rules/*.md` when
  working in that area; OpenCode does not load Claude Code rules automatically.
- Run the same `scripts/swe_guard.py` pin/snapshot/begin/finish commands and
  record the same Artifact, Gate, and Checkpoint evidence. Before ending a
  session with managed Artifacts, run the closure check described in
  `docs/opencode.md` because OpenCode has no Claude Code Stop hook.
- Claude Code-only syntax below (`Agent(...)`, `.claude/settings.json`,
  `PreToolUse`, and `/hooks`) describes the Claude runtime. Use the OpenCode
  equivalents above while keeping all engineering requirements.

---

"""


def parse_agent(source: Path) -> tuple[dict[str, str], str]:
    content = source.read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", content, re.S)
    if not match:
        raise ValueError(f"invalid frontmatter: {source}")
    fields = {}
    for line in match.group(1).splitlines():
        key, separator, value = line.partition(":")
        if separator:
            fields[key.strip()] = value.strip()
    if fields.get("name") != source.stem or not fields.get("description"):
        raise ValueError(f"invalid name/description: {source}")
    return fields, match.group(2)


def render_agent(source: Path) -> str:
    fields, body = parse_agent(source)
    name = fields["name"]
    tools = {item.strip() for item in fields.get("tools", "").split(",")}
    permissions = [
        ("subagent", "deny"),
        ("edit", "deny" if name in READ_ONLY or not ({"Write", "Edit"} & tools) else "allow"),
        ("shell", "allow" if "Bash" in tools else "deny"),
    ]
    lines = [
        "---",
        f"description: {json.dumps(fields['description'], ensure_ascii=False)}",
        "mode: subagent",
        "permissions:",
    ]
    for action, effect in permissions:
        lines += [f"  - action: {action}", '    resource: "*"', f"    effect: {effect}"]
    lines += ["---", "", AGENT_HEADER.replace("<name>", name), "", body.strip()]
    return "\n".join(lines) + "\n"


def expected_files() -> dict[Path, str]:
    agents = sorted(SOURCE_AGENTS.glob("*.md"))
    if len(agents) != 15:
        raise ValueError(f"expected 15 source agents, found {len(agents)}")
    result = {TARGET_AGENTS / agent.name: render_agent(agent) for agent in agents}
    result[ROOT / "AGENTS.md"] = HEADER + BRIDGE + (ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    expected = expected_files()
    stale = [path for path, content in expected.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
    if args.check:
        if stale:
            print("Stale OpenCode files: " + ", ".join(str(path.relative_to(ROOT)) for path in stale), file=sys.stderr)
            return 1
        print("OpenCode files are in sync")
        return 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected[path], encoding="utf-8")
    print(f"Updated {len(stale)} OpenCode files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
